//! **MCP 桥**：让框架用上整个 MCP 生态（附录 §10）。
//!
//! §10 早就把关系定死了，这一版就是照着它写的：
//!
//! > **MCP server 是框架里的一个 kind，注册后自动带来它的工具实例**，
//! > 照样受绑定与权限约束。**框架是 MCP 的宿主，不是替代品。**
//!
//! 落地形状：**一个披着工具服务外衣的 MCP 客户端**。
//!
//! ```text
//!   智能体 ──(我们的协议)──▶ 桥（本进程）──(MCP/JSON-RPC over stdio)──▶ MCP server
//! ```
//!
//! 它**不做翻译成自己的方言**，也不把 MCP 工具塞进一个通用调度器：
//! 启动时问一次 `tools/list`，然后**把每个 MCP 工具原样报成我们的工具** ——
//! 于是名片、`help`、能力、绑定、契约闸门那一整套**一个字都不用改**就能管住它们。
//! 这直接回答了待定 #49（渐进披露）：**声明通道保留，渐进披露由我们这层给**。
//!
//! 三条 MCP 表达不了的东西（§10.2：结果契约 / 主动事件 / 渐进披露），
//! 前两条由**宿主层**补：`effect` / `route` 是我们加的，主动事件由服务这层发。


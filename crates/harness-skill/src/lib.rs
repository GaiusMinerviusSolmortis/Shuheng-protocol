//! **技能**：一个目录里的"怎么做某类事"（01-内核 §3 那张实例清单里的"技能"）。
//!
//! §3 给它的定义是"**一份怎么做某类事的知识/流程，可能带示例与工具绑定**，
//! 版本化，不需要常驻"。落地成一个**服务实例**（和记忆那一层同形）：
//! 目录里的每个子目录是一个技能，服务按章把它们借出去。
//!
//! 为什么"按章"这么重要 —— 那是你最早提的那条：
//!
//! > 智能体在提示词阶段就被告知它有这个工具，以及**该如何去获取它的相关知识** ——
//! > 有点像面对一个不熟的工具，打出工具名加 `--help`。
//!
//! 所以 `list` 只给**名字 + 一句话**（名片），`open` 不带章给**章节目录**，
//! `open` 带章才给正文，而且**正文可以分页**（一行一行给，不是一坨砸过去）。
//! 一次全倒出来会把上下文吃掉 —— 这条在 §5.3 就叫渐进披露。
//!
//! 两种技能目录都收（**不为格式重写一遍别人的东西**）：
//!
//! | 形状 | 什么时候用 |
//! |---|---|
//! | 一个 `skill.json` + 若干 `.md` | 要写清 `version` / `when_to_use` / 章的顺序 |
//! | **只有一个 `SKILL.md`** | 现成的那些技能目录 —— **按 `## ` 标题自动切章**，抄过来就能用 |


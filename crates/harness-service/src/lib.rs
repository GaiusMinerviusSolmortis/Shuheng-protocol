//! 工具服务的**公共件**。
//!
//! 抽出来的理由很直接：**围栏和域锁是两个服务都要用的东西，
//! 而安全代码有两份就一定会漂移。**
//!
//! | 件 | 是什么 | 出处 |
//! |---|---|---|
//! | [`fence`] | 路径围栏：读写都必须在托管路径内 | 04-安全 §7.1 |
//! | [`domain_lock`] | 域锁：同一个域只能有一个服务进程 | 02-工具 §5.15 第五节 |
//! | [`grant`] | 凭证：中控签发，**服务自己校验** | 04-安全 §7 |
//! | [`contract`] | **契约闸门**：manifest 合不合规、结果合不合自己声明的形 | 规范-工具服务 §11.1 / §11.3 |
//! | [`job`] | **一棵进程树**：放进 Job Object，能整棵掐、能上硬限额 | 04-安全 §5.8 决定二 |
//! | [`inherit`] | **别让子进程顺走我们的句柄**：拉起之前摘掉可继承位 | 规范-消息协议 §6.3 |
//! | [`reply`] | **"这是哪种错"**：没给参数 / 实例不存在 / 参数是空的 —— 三种说法要一致 | 规范-工具服务 §11.5 |
//!
//! 这里**不放**协议、不放消息循环 —— 那些归 `harness-core` 和各服务自己。

pub mod contract;
pub mod domain_lock;
pub mod fence;
pub mod grant;
pub mod job;
pub mod inherit;
pub mod reply;
